const fortunePrompts = Object.entries(fortuneCategories).flatMap(([category, { prompts }]) =>
  prompts.map((text) => ({ category, text })));
export const fortunePromptCount = fortunePrompts.length;

export function pickFortune(category, recent, random = secureIndex) {
  const pool = category ? fortunePrompts.filter((prompt) => prompt.category === category) : fortunePrompts;
  const available = pool.filter(({ text }) => !recent.includes(text));
  const choices = available.length ? available : pool;
  return choices[random(choices.length)];
}
